CREATE TABLE IF NOT EXISTS accounts (
 id UUID PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, display_name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(100) NOT NULL, recovery_hash VARCHAR(64) NOT NULL,
 role VARCHAR(24) NOT NULL, scope VARCHAR(36) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS sessions (
 digest VARCHAR(64) PRIMARY KEY, account_id UUID NOT NULL REFERENCES accounts(id), expires_at BIGINT NOT NULL
);
