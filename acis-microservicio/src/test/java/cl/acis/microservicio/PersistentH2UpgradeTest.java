package cl.acis.microservicio;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertNotEquals;

import cl.acis.microservicio.dto.OrderRequest;
import cl.acis.microservicio.dto.OrderResponse;
import cl.acis.microservicio.model.Stage;
import cl.acis.microservicio.model.WorkOrder;
import cl.acis.microservicio.repository.WorkOrderRepository;
import cl.acis.microservicio.service.OrderService;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;

class PersistentH2UpgradeTest {
    @Test
    void schemaUpdatePreservesLegacyOrdersAndNewOrdersAcrossRestart(@TempDir Path temporaryDirectory) throws Exception {
        String databasePath = temporaryDirectory.resolve("fictional-acis-db").toAbsolutePath()
                .toString().replace('\\', '/');
        String jdbcUrl = "jdbc:h2:file:" + databasePath + ";DB_CLOSE_ON_EXIT=FALSE";
        createLegacySchemaWithFictionalOrder(jdbcUrl);

        long createdOrderId;
        String clientOrderId = UUID.randomUUID().toString();
        try (ConfigurableApplicationContext context = startApplication(jdbcUrl)) {
            WorkOrderRepository repository = context.getBean(WorkOrderRepository.class);
            WorkOrder legacy = repository.findById(417L).orElseThrow();
            assertLegacyOrderUnchanged(legacy);
            assertNull(legacy.getClientOrderId());

            OrderRequest request = newFictionalRequest(clientOrderId);
            OrderResponse created = context.getBean(OrderService.class).create(request);
            createdOrderId = created.id();
            assertNotEquals(417L, createdOrderId);
            assertEquals(clientOrderId, created.clientOrderId());
            assertEquals("Local ficticio nuevo", created.site());
        }

        try (ConfigurableApplicationContext restartedContext = startApplication(jdbcUrl)) {
            WorkOrderRepository repository = restartedContext.getBean(WorkOrderRepository.class);
            assertEquals(2, repository.count());
            assertLegacyOrderUnchanged(repository.findById(417L).orElseThrow());

            WorkOrder created = repository.findById(createdOrderId).orElseThrow();
            assertEquals(clientOrderId, created.getClientOrderId());
            assertEquals("Local ficticio nuevo", created.getSite());
            assertEquals(Stage.ASSIGNED, created.getStage());
            assertFalse(created.isCustomerConfirmed());
            assertEquals(0, created.getEvidenceCount());
        }
    }

    private static ConfigurableApplicationContext startApplication(String jdbcUrl) {
        return new SpringApplicationBuilder(AcisMicroservicioApplication.class)
                .web(WebApplicationType.NONE)
                .run("--spring.datasource.url=" + jdbcUrl,
                        "--spring.datasource.driver-class-name=org.h2.Driver",
                        "--spring.datasource.username=sa",
                        "--spring.datasource.password=",
                        "--spring.jpa.hibernate.ddl-auto=update",
                        "--spring.jpa.open-in-view=false",
                        "--spring.main.banner-mode=off",
                        "--logging.level.root=ERROR");
    }

    private static void createLegacySchemaWithFictionalOrder(String jdbcUrl) throws Exception {
        try (Connection connection = DriverManager.getConnection(jdbcUrl, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE ordenes (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        site VARCHAR(255) NOT NULL,
                        address VARCHAR(255) NOT NULL,
                        equipment VARCHAR(255) NOT NULL,
                        technician VARCHAR(255) NOT NULL,
                        priority VARCHAR(255) NOT NULL,
                        type VARCHAR(255) NOT NULL,
                        problem VARCHAR(2000) NOT NULL,
                        stage VARCHAR(255) NOT NULL,
                        diagnosis VARCHAR(2000) NOT NULL,
                        work VARCHAR(2000) NOT NULL,
                        materials VARCHAR(2000) NOT NULL,
                        location VARCHAR(500) NOT NULL,
                        arrival BIGINT NOT NULL,
                        departure BIGINT NOT NULL,
                        customer VARCHAR(200) NOT NULL,
                        feedback VARCHAR(2000) NOT NULL,
                        customer_confirmed BOOLEAN NOT NULL,
                        evidence_count INTEGER NOT NULL
                    )
                    """);
            try (PreparedStatement insert = connection.prepareStatement("""
                    INSERT INTO ordenes(id,site,address,equipment,technician,priority,type,problem,stage,
                        diagnosis,work,materials,location,arrival,departure,customer,feedback,
                        customer_confirmed,evidence_count)
                    VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                    """)) {
                insert.setLong(1, 417L);
                insert.setString(2, "Local ficticio legado");
                insert.setString(3, "Dirección de prueba 123");
                insert.setString(4, "Equipo legado");
                insert.setString(5, "Técnico ficticio");
                insert.setString(6, "Alta");
                insert.setString(7, "Correctiva");
                insert.setString(8, "Falla ficticia anterior");
                insert.setString(9, "DONE");
                insert.setString(10, "Diagnóstico legado");
                insert.setString(11, "Trabajo legado");
                insert.setString(12, "Material de prueba");
                insert.setString(13, "-33.4,-70.6");
                insert.setLong(14, 1700000000L);
                insert.setLong(15, 1700003600L);
                insert.setString(16, "Cliente ficticio");
                insert.setString(17, "Conforme");
                insert.setBoolean(18, true);
                insert.setInt(19, 2);
                insert.executeUpdate();
            }
        }
    }

    private static void assertLegacyOrderUnchanged(WorkOrder legacy) {
        assertEquals(417L, legacy.getId());
        assertEquals("Local ficticio legado", legacy.getSite());
        assertEquals("Dirección de prueba 123", legacy.getAddress());
        assertEquals("Equipo legado", legacy.getEquipment());
        assertEquals("Técnico ficticio", legacy.getTechnician());
        assertEquals("Alta", legacy.getPriority());
        assertEquals("Correctiva", legacy.getType());
        assertEquals("Falla ficticia anterior", legacy.getProblem());
        assertEquals(Stage.DONE, legacy.getStage());
        assertEquals("Diagnóstico legado", legacy.getDiagnosis());
        assertEquals("Trabajo legado", legacy.getWork());
        assertEquals("Material de prueba", legacy.getMaterials());
        assertEquals("-33.4,-70.6", legacy.getLocation());
        assertEquals(1700000000L, legacy.getArrival());
        assertEquals(1700003600L, legacy.getDeparture());
        assertEquals("Cliente ficticio", legacy.getCustomer());
        assertEquals("Conforme", legacy.getFeedback());
        assertEquals(2, legacy.getEvidenceCount());
        assertEquals(true, legacy.isCustomerConfirmed());
    }

    private static OrderRequest newFictionalRequest(String clientOrderId) {
        OrderRequest request = new OrderRequest();
        request.setClientOrderId(clientOrderId);
        request.setSite("Local ficticio nuevo");
        request.setAddress("Dirección de prueba 456");
        request.setEquipment("Equipo ficticio nuevo");
        request.setTechnician("Técnico de prueba");
        request.setPriority("Normal");
        request.setType("Preventiva");
        request.setProblem("Orden de prueba ficticia");
        request.setStage(Stage.ASSIGNED);
        return request;
    }
}
